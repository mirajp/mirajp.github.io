/** Clamps and rounds every slider parameter to its legal `[min, max]` range. */
export function clampValues(values: Readonly<PartialParamValues>): ParamValues {
  const out = neutralValues();
  for (const p of PARAMS) {
    const raw = values[p.key] ?? 0;
    const finite = Number.isFinite(raw) ? raw : 0;
    out[p.key] = Math.min(p.max, Math.max(p.min, Math.round(finite)));
  }
  return out;
}

/** Returns true when all non-fixed image adjustment parameters are `0`. */
export function isNeutral(values: Readonly<ParamValues>): boolean {
  return PARAMS.every((p) => p.fixed === true || values[p.key] === 0);
}

/** Mixes a preset at `strength` percent (`0..150`) with manual per-slider tweaks. */
export function mixValues(
  presetId: string,
  strength: number,
  tweak: Readonly<PartialParamValues> | null,
): ParamValues {
  const raw: PartialParamValues = {};
  const preset = presetId ? PRESET_BY_ID[presetId] : undefined;
  for (const p of PARAMS) {
    const scale = p.fixed ? (strength > 0 ? 1 : 0) : strength / 100;
    const base = preset ? (preset.values[p.key] ?? 0) * scale : 0;
    raw[p.key] = base + (tweak?.[p.key] ?? 0);
  }
  return clampValues(raw);
}
